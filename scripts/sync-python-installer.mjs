import { readFileSync, writeFileSync } from 'node:fs';

const read = name => readFileSync(new URL('../' + name, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const header = '// Generated by scripts/sync-python-installer.mjs. Do not edit directly.\n';
const outputs = {
  'src/data/pythonInstaller.ts': header + 'export default ' + JSON.stringify(read('INSTALL_PYTHON.bat')) + ';\n',
  'src/data/pythonBridgeScript.ts': header + 'export const PYTHON_BRIDGE_SCRIPT = ' + JSON.stringify(read('praj_desktop_bridge.py')) + ';\n',
  'src/data/windowsScripts.ts': header + ['START_PRAJ', 'KILL_PRAJ', 'PRAJ_MASTER_SWITCH', 'PRAJ_SWITCH']
    .map(name => 'export const ' + name + '_BAT = ' + JSON.stringify(read(name + '.bat')) + ';\n').join(''),
};
for (const [name, generated] of Object.entries(outputs)) {
  const target = new URL('../' + name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== generated) {
      throw new Error(name + ' is stale. Run npm run sync:installer.');
    }
  } else {
    writeFileSync(target, generated);
  }
}
